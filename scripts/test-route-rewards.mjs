import assert from 'node:assert/strict';
import {transactionReward} from '../data/route-rewards.mjs';
const calc=(cardId,routeId,amount,used=0)=>transactionReward({cardId,routeId,amount,used,eligible:true});
assert.equal(calc('amazon-icici','amazon-prime',10000).reward,500);
assert.equal(calc('amazon-icici','amazon-nonprime',10000).reward,300);
assert.equal(calc('amazon-icici','amazon-prime',99).reward,4);
assert.equal(calc('amazon-icici','retail',10000).reward,100);
assert.equal(calc('hdfc-millennia','partner',99).reward,0);
assert.equal(calc('hdfc-millennia','partner',199).reward,5);
assert.equal(calc('hdfc-millennia','partner',5000,950).reward,50);
assert.equal(calc('hdfc-millennia','retail',5000).reward,50);
assert.equal(calc('axis-ace','googlepay',10000).reward,500);
assert.equal(calc('axis-ace','delivery',5000,400).reward,100);
assert.equal(calc('axis-ace','retail',10000,500).reward,150);
assert.equal(calc('axis-ace','delivery',39).reward,2);
assert.equal(calc('sbi-cashback','online',80000).reward,2000);
assert.equal(calc('sbi-cashback','offline',10000).reward,100);
assert.equal(calc('sbi-cashback','online',10000,2000).reward,0);
assert.equal(transactionReward({cardId:'axis-ace',routeId:'delivery',amount:1000}).unavailable,true);
for(const amount of [-1,NaN,Infinity])assert.throws(()=>calc('axis-ace','delivery',amount),RangeError);
assert.throws(()=>calc('axis-ace','wrong',100),RangeError);
assert.throws(()=>calc('wrong','delivery',100),RangeError);
console.log('Transaction reward checks passed: eligible routes, block rounding, shared caps, excluded contexts and invalid inputs.');
