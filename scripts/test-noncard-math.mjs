import assert from "node:assert/strict";
import {fdScenario,insuranceScenario,calcSIP,calcLumpsum} from "../data/noncard-math.mjs";
assert.equal(calcSIP(10000,0,1).maturity,120000);
assert.equal(calcLumpsum(100000,12,1).maturity,112000);
const monthlyRate=Math.pow(1.12,1/12)-1;
const summed=Array.from({length:12},(_,i)=>10000*Math.pow(1+monthlyRate,12-i)).reduce((a,b)=>a+b,0);
assert.equal(calcSIP(10000,12,1).maturity,Math.round(summed));
const fd={amount:100000,fdRate:7.5,taxBracket:30,inflation:5,tenure:1,isSenior:false};
assert.equal(fdScenario(fd).realReturn,"0.24");
assert.equal(fdScenario(fd).purchasingPower,100238);
assert.equal(fdScenario({...fd,inflation:0}).realReturn,"5.25");
assert.equal(fdScenario({...fd,tenure:3}).realReturn,((Math.pow(1.1575,1/3)/1.05-1)*100).toFixed(2));
const claim={sumInsured:1000000,claimAmount:1500000,copay:0,roomRentCap:8000,chosenRoomRent:8000,diseaseSubLimit:100,proportionateClauseApplies:false};
assert.equal(insuranceScenario(claim).aboveSumInsured,500000);
assert.equal(insuranceScenario(claim).outOfPocket,500000);
assert.equal(insuranceScenario(claim).claimAmount,1500000);
assert.equal(insuranceScenario({...claim,claimAmount:500000,copay:20}).finalPayout,400000);
assert.equal(insuranceScenario({...claim,claimAmount:0}).finalPayout,0);
console.log("Non-card tests passed: exact FD purchasing power and above-limit insurance claims.");
